"""Compiler A: CompiledAgent -> NeMo Agent Toolkit workflow (the YAML `nat run` and `nat eval` read).

Least privilege: each MCP server exposes ONLY the tools the spec asked for (`include`), even if the server offers
more.
"""

from __future__ import annotations

from typing import Any

import yaml

from agentbuilder.compile.compiled import CompiledAgent

_WORKFLOW_TYPE = {"tool_calling": "tool_calling_agent", "react": "react_agent"}


def to_nat_workflow(c: CompiledAgent) -> dict[str, Any]:
    function_groups: dict[str, Any] = {}
    for server in c.servers:
        function_groups[server.name] = {
            "_type": "mcp_client",
            "server": {"transport": "stdio", "command": server.command, "args": list(server.args)},
            "include": [t.mcp_name for t in c.tools_for(server.name)],
        }
    llm: dict[str, Any] = {"_type": "openai", "model_name": c.model.model, "base_url": c.model.base_url}
    if c.model.api_key_env:
        llm["api_key"] = "${" + c.model.api_key_env + "}"
    if c.model.temperature is not None:
        llm["temperature"] = c.model.temperature
    if c.model.max_tokens is not None:
        llm["max_tokens"] = c.model.max_tokens
    workflow: dict[str, Any] = {
        "_type": _WORKFLOW_TYPE[c.model.agent_mode],
        "tool_names": [s.name for s in c.servers],
        "llm_name": "main_llm",
    }
    if c.model.agent_mode == "react":
        workflow["parse_agent_response_max_retries"] = c.parse_retries
    if c.instructions:
        workflow["additional_instructions"] = c.instructions
    out: dict[str, Any] = {}
    if function_groups:
        out["function_groups"] = function_groups
    out["llms"] = {"main_llm": llm}
    out["workflow"] = workflow
    return out


def to_nat_yaml(c: CompiledAgent) -> str:
    header = (
        f"# Generated by agentbuilder from agent '{c.name}' (spec_version {c.spec_version}). "
        "Do not edit; edit the spec.\n"
    )
    return header + yaml.safe_dump(to_nat_workflow(c), sort_keys=False, allow_unicode=True, default_flow_style=False)
