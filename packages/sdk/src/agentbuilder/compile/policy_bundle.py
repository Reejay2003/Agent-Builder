"""Compiler D, part 1: the per-tool-call authorization policy as an OPA bundle (PLAN 4.2, section 10).

`tool_decision` (compiler.py) is the rule; this writes the same decisions as data plus a small Rego policy, so an OPA
in front of the tools (a future MCP gateway) answers exactly what the SDK's own tool servers enforce today. Tests run
the bundle in a real OPA and compare every answer with `tool_decision`.

    input:  {"tool": "calendar.create_event", "mock": false, "approved": false}
    output: data.agentbuilder.decision -> "allow" | "ask" | "deny"
"""

from __future__ import annotations

import json
from typing import Any

from agentbuilder.compile.compiled import CompiledAgent
from agentbuilder.compile.compiler import tool_decision

REGO = """package agentbuilder

import rego.v1

# Generated by agentbuilder (compiler D). The decisions live in data.json; this file never changes per agent.
default decision := "deny"

tool := data.agentbuilder.tools[input.tool]

# A listed tool in mock mode touches nothing live.
decision := "allow" if {
\ttool
\tinput.mock == true
}

decision := tool.decision if {
\tinput.mock != true
\tnot asked_and_approved
}

# "ask" becomes "allow" once a person approved this very call.
decision := "allow" if {
\tinput.mock != true
\tasked_and_approved
}

asked_and_approved if {
\ttool.decision == "ask"
\tinput.approved == true
}
"""


def to_policy_data(c: CompiledAgent) -> dict[str, Any]:
    return {
        "agentbuilder": {
            "agent": c.name,
            "tools": {
                t.id: {"decision": tool_decision(c, t), "risk_tier": t.risk_tier, "server": t.server} for t in c.tools
            },
        }
    }


def to_opa_bundle(c: CompiledAgent) -> dict[str, str]:
    """File name -> content of an OPA bundle directory (`opa run --bundle <dir>` or `opa eval -b <dir>`)."""
    return {"policy.rego": REGO, "data.json": json.dumps(to_policy_data(c), indent=2, sort_keys=True) + "\n"}
